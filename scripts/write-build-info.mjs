// Generates src/generated/build-info.ts with a non-sensitive build identifier.
// Run before each build: node scripts/write-build-info.mjs
import { execSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

function commitId() {
  try {
    return execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim();
  } catch {
    return "no-git";
  }
}

// Bump this when a migration changes the public schema/entities contract.
const SCHEMA_VERSION = "v1";

const info = {
  commit: commitId(),
  builtAt: new Date().toISOString(),
  schemaVersion: SCHEMA_VERSION,
};

mkdirSync(`${root}src/generated`, { recursive: true });
writeFileSync(
  `${root}src/generated/build-info.ts`,
  `// GENERATED by scripts/write-build-info.mjs — do not edit by hand.
export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;
`
);
console.log(`build-info: ${info.commit} @ ${info.builtAt} (schema ${info.schemaVersion})`);
