const SHARED = Object.fromEntries(
  SHARED_SOURCES.map((name) => [name.replace(".ts", ""), stripAllImports(read(`supabase/functions/_shared/${name}`))])
);

const header = `// GENERATED by scripts/bundle-functions.mjs — do not edit by hand.\n// Edit supabase/functions/_shared/* and <fn>/source.ts, then re-run the bundler.\n\n`;

let failures = 0;
for (const [name, deps] of Object.entries(FNS)) {
  const body = stripSharedImports(read(`supabase/functions/${name}/source.ts`));
  const out = `${header}${[...deps.map((d) => SHARED[d]), body].join("\n\n")}`;
  const onDisk = read(`supabase/functions/${name}/index.ts`);

  if (onDisk !== out) {
    failures += 1;
    console.error(`[drift] ${name}: index.ts is stale vs source.ts/_shared — run node scripts/bundle-functions.mjs`);
  }
  if (!out.includes("Deno.serve(")) {
    failures += 1;
    console.error(`[entry] ${name}: bundled output has no Deno.serve( entry point`);
  }
}

// Hand-authored entry points (no source.ts to bundle).
for (const name of ["me", "candidate-status"]) {
  const src = read(`supabase/functions/${name}/index.ts`);
  if (!src.includes("Deno.serve(")) {
    failures += 1;
    console.error(`[entry] ${name}: index.ts has no Deno.serve( entry point`);
  }
}

if (failures > 0) {
  console.error(`check-functions: ${failures} failure(s) — fix before deploying.`);
  process.exit(1);
}
console.log(`check-functions: all ${Object.keys(FNS).length + 2} function entry points bundled & valid (${SHARED_SOURCES.length} shared modules).`);
