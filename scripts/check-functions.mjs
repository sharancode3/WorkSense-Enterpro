// Phase 0: validate backend function ENTRY POINTS (not just shared helpers).
//
// 1. Re-bundles every function in memory using the same dependency map as
//    scripts/bundle-functions.mjs and fails if the committed index.ts is stale
//    relative to source.ts + _shared/*.
// 2. Asserts every deployed entry point actually defines Deno.serve (a bundle
//    without an entry handler would deploy but never respond).
//
// The type check over source.ts + _shared runs via tsconfig.functions-check.json
// (`tsc -p tsconfig.functions-check.json`) — run both from `check:functions`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(`${root}${p}`, "utf8");

const stripAllImports = (src) => src.replace(/^import .*;$/gm, "");
const stripSharedImports = (src) =>
  src
    .replace(/import\s*\{[^}]*\}\s*from\s*"\.\.\/_shared\/[^"]+";/gs, "")
    .replace(/^import .* from "\.\.\/_shared\/.*";$/gm, "");

